#!/usr/bin/env python3
"""Generate failure_notes/reports/VR-<version>.md KPI sections from the evidence store. Usage: python -m scripts.make_vr v0"""
import glob, json, sys
from pathlib import Path
from utils import kpi_eval, results_store

ROOT = Path(__file__).resolve().parent.parent
ver = sys.argv[1] if len(sys.argv) > 1 else "v0"
runs = results_store.latest_by_kpi(results_store.load_runs(), version=ver)
sc = kpi_eval.scorecard(runs); sm = kpi_eval.summarize(sc)
fmt = lambda v: "—" if v is None else (f"{v:.3f}" if isinstance(v, float) else str(v))
icon = {"PASS": "✅ PASS", "FAIL": "❌ FAIL", "NO_DATA": "⚪ NO DATA (counts as FAIL in certification)", "INFORMATIONAL": "🔵 INFORMATIONAL (not certifiable)", "NO_EVIDENCE": "🟠 NO EVIDENCE"}
tbl = "\n".join(f"| {r['kpi'][4:]} | {r['name']} | {r['target']} | {fmt(r['value'])} | {r['n'] or '—'} | {r['profile'] or '—'} | {r['run_id'] or '—'} | {r['artifact'] or '—'} | {icon[r['status']]} |" for r in sc)
pat = {"v0": "_extractive", "v0.2": "_v02_gptoss20b"}.get(ver, "")
g = json.load(open(sorted(glob.glob(f"artifacts/golden_eval_*{pat}.json"))[-1]))
strat = "\n".join(f"| {k} | n/a (extractive quotes) | {fmt(v['relevancy'])} | {fmt(v['entity_recall'])} | {fmt(v['answered'])} |" for k, v in g["per_stratum"].items())
IT = {"v0": "I1", "v0.1": "I2", "v0.2": "I3"}.get(ver, "?")
GEN = "deterministic extractive (ADR-7 bake-off NOT run)" if ver == "v0" else "openai/gpt-oss-20b via Groq (routed; ADR-7 bake-off run; dev stand-in for the self-hosted target model)"
HIGH = {"v0": "L1 (partial: system tests 16/16, rollback drill 5/5); L0 benches run; **L2–L6 NOT RUN**", "v0.2": "L1 (system tests, rollback drill, red team on live stack); L0 benches; k6 smoke only; **L2–L6 NOT RUN (needs GPU + distributed injectors)**"}.get(ver, "see narrative")
TESTS = {"v0": "pytest 26 (25 pass; live-workbench test is timing-sensitive and passes in isolation) · system tests 16/16", "v0.2": "see narrative (filled from the final run)"}.get(ver, "")
out = f"""# VR-{ver} — Version Report (iteration {IT})

> Generated by `scripts/make_vr.py` from `artifacts/kpi_runs.jsonl`. **Nothing here is certified**: the host is CPU-only (profile `dev-cpu`), L2–L6 were NOT RUN, RAGAS KPIs are proxies. See `failure_notes/FN-{ver}-*.md`.

| Field | Value |
|---|---|
| Version | {ver} (design D1.0, lock sha256 in DESIGN.lock) |
| Profile / hardware | dev-cpu · 4 vCPU · 15 GB · no GPU · time dilation ×20 on loop/step/MCP budgets |
| Models | bi-encoder BAAI/bge-small-en-v1.5 · reranker cross-encoder/ms-marco-MiniLM-L-6-v2 (ONNX fp32) · NLI deberta-v3-small · injection clf protectai/deberta-v3-base-prompt-injection-v2 · generation: **{GEN}** |
| Highest rung | {HIGH} |
| KPI summary | PASS {sm['PASS']} · FAIL {sm['FAIL']} · INFORMATIONAL {sm['INFORMATIONAL']} · NO DATA {sm['NO_DATA']} · certified = **{sm['certified']}** |
| Build-time adherence | 28/28 (`python -m scripts.audit_check`) |
| Tests | {TESTS} |

## 1. All 36 KPIs (blank = NO DATA)
| # | KPI | Target | Measured | N | Profile | Run id | Artifact | Status |
|---|---|---|---|---|---|---|---|---|
{tbl}

## 2. Golden-250 (proxies, not RAGAS) per stratum
Overall: relevancy-proxy {g['answer_relevancy_proxy']:.3f} · entity recall {g['context_entity_recall']:.3f} · abstention accuracy {g['abstention_accuracy_pct']:.1f}% (37 negatives) · hallucination (numeric grounding) {g['hallucination_rate_pct']:.2f}% · mean steps {g['mean_steps']:.2f} · token reduction {g.get('token_reduction_pct', 0):.1f}%.

| Stratum | Faithfulness | Relevancy proxy | Entity recall | Answered |
|---|---|---|---|---|
{strat}

Faithfulness is 1.0 by construction for verbatim extractive quotes — **not evidence** about a generative model.

## 3. Security & isolation
Red team (seed 100 prompts × mutators, 1,040 block executions): 0 misses — but seeds were tuned-on; **holdout 160 executions: 66.9% blocked** (KPI-03 FAIL). PII fixtures 1,500/1,500 redacted (95% upper bound on miss rate ≈0.2%). Benign false-positive refusal 7.5% (FAIL). Cross-tenant: 0 leaks in 121 probes incl. a 120-request concurrent storm. Tier-3 executed without approval: 0 of 11 checks.

## 4. Rollback drill (L1)
config snapshot ✔ · index N-1 swap ✔ (7.8 s) · DB migration down→up (scratch schema) ✔ · cache namespace bump ✔ · code rollback to tag ✔ (tag checked out in a scratch worktree; design lock matches; sources compile).

## 5. Failure notes
FN-{ver}-001 KPI-01 latency · 002 KPI-03/06 injection (Sev-1) · 003 KPI-13 nDCG · 004 KPI-24 hallucination · 005 KPI-20/21 generation/ADR-7 blocked · 006 KPI-30 MCP overhead · 007 NOT RUN scope · 008 defects fixed in v0.

## 6. Audit claims (see audit/CLAIMS_REGISTER.md → "Status after VR-{ver}")
All 20 claims remain UNVERIFIED or contradicted by measurement; none is marked PASS from the audit document.

## 7. Fix list for I2 (v0.1), ordered by impact on accuracy and p95/p99 at 50K
1. Working LLM provider + ADR-7 bake-off + real RAGAS (FN-005) — accuracy is the primary objective.
2. Injection classifier generalisation + benign calibration on a frozen holdout (FN-002, Sev-1).
3. Pre-hook latency: classifier off the critical path / distilled (FN-001).
4. Hallucination measurement/serving disagreement (FN-004) and nDCG (FN-003).
5. MCP overhead floor (FN-006). 6. Move to `target` hardware and run L2→L5 (FN-007).

## 8. Open gaps / owner decisions
OpenRouter guardrail/data policy blocks all probed models; no Groq key. GPU type/count. Git identity + GitHub credentials. Whether to bump the design to allow complexity-based routing to a larger model (ADR-7 currently rejects it).
"""
nar = ROOT / "failure_notes/reports" / f"NARRATIVE-{ver}.md"
if nar.exists():
    out = out[:out.index("## 3. Security & isolation")] + nar.read_text()
p = ROOT / "failure_notes/reports" / f"VR-{ver}.md"; p.write_text(out); print("wrote", p, "| PASS", sm["PASS"], "FAIL", sm["FAIL"], "INFO", sm["INFORMATIONAL"], "NO_DATA", sm["NO_DATA"])
